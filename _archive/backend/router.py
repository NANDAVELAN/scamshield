"""LLM Router with multi-tier fallback chain (Gemini Pro -> Ollama Local -> Rules), retry logic, and PII redaction."""
import os
import time
import asyncio
import logging
from typing import Dict, Any, Optional, Callable
from google.adk.models.lite_llm import LiteLlm
from google.adk.runners import InMemoryRunner
from google.genai import types

from .schemas import Message, Verdict, Evidence
from .rules_engine import analyze_rules
from .guardrails import redact_pii, detect_prompt_injection, validate_verdict
from .agent_graph import build_scamshield_agent

logger = logging.getLogger("scamshield.router")

def get_provider_chain():
    """Build ordered fallback list based on available API keys."""
    providers = []
    
    # 1. Gemini Pro (Direct Google GenAI)
    gemini_key = os.getenv("GEMINI_API_KEY", "") or os.getenv("GOOGLE_API_KEY", "")
    if gemini_key and gemini_key != "your_gemini_api_key_here":
        providers.append({
            "name": "Gemini Pro",
            "fast": "gemini-2.5-flash",
            "strong": "gemini-2.5-pro",
            "requires_key": True
        })

    # 2. Local Ollama Fallback (Offline Private Inference)
    ollama_base = os.getenv("OLLAMA_API_BASE", "http://localhost:11434")
    providers.append({
        "name": "Ollama Local",
        "fast": LiteLlm(model=os.getenv("OLLAMA_MODEL", "ollama_chat/qwen2.5:7b")),
        "strong": LiteLlm(model=os.getenv("OLLAMA_MODEL", "ollama_chat/qwen2.5:7b")),
        "requires_key": False
    })

    return providers

async def execute_adk_pipeline(provider: Dict[str, Any], message: Message, broadcast_callback: Optional[Callable] = None) -> Verdict:
    """Runs the Google ADK root agent graph with guarded input and exponential backoff retry."""
    agent = build_scamshield_agent(provider["fast"], provider["strong"])
    runner = InMemoryRunner(agent=agent)
    session_id = f"sess_{int(time.time() * 1000)}"
    user_id = "analyst"

    # Redact PII before cloud transmission
    safe_body = redact_pii(message.body)

    prompt = (
        f"Incoming alert:\n"
        f"Channel: {message.channel}\n"
        f"Sender: {message.sender}\n"
        f"Body: {safe_body}\n"
        f"URLs: {message.urls}\n"
        f"Attachments: {[a.name for a in message.attachments]}\n"
    )

    user_content = types.Content(
        role="user",
        parts=[types.Part.from_text(text=prompt)]
    )

    final_verdict = None

    # Retry loop with backoff (up to 2 retries)
    for attempt in range(2):
        try:
            async for event in runner.run_async(user_id=user_id, session_id=session_id, new_message=user_content):
                if broadcast_callback:
                    # Stream agent activities
                    if hasattr(event, "author") and event.author:
                        await broadcast_callback(event.author, "Processing stage findings...", stage=2)
            
            # Fetch structured verdict from session state
            session = await runner._get_or_create_session(user_id=user_id, session_id=session_id)
            if session and hasattr(session, "state") and "verdict" in session.state:
                raw_v = session.state["verdict"]
                if isinstance(raw_v, Verdict):
                    final_verdict = raw_v
                elif isinstance(raw_v, dict):
                    final_verdict = Verdict.model_validate(raw_v)
            break
        except Exception as e:
            logger.warning(f"Provider {provider['name']} attempt {attempt+1} failed: {e}")
            if attempt == 0:
                await asyncio.sleep(1.0)
            else:
                raise e

    if not final_verdict:
        raise RuntimeError("No structured verdict generated by ADK agent")

    final_verdict.mode = "llm"
    return final_verdict

async def analyze_with_agent_router(message: Message, broadcast_callback: Optional[Callable] = None) -> Verdict:
    """Routes analysis through configured fallback chain: Gemini Pro -> Ollama Local -> Rules."""
    mode = os.getenv("MODE", "rules").lower()
    
    # Check injection signal upfront
    is_injected, reason = detect_prompt_injection(message.body)
    if is_injected:
        if broadcast_callback:
            await broadcast_callback("Guardrails", f"Flagged adversarial prompt injection: {reason}", stage=0)
        return analyze_rules(message)

    if mode == "rules":
        if broadcast_callback:
            await broadcast_callback("Router", "MODE=rules. Using rules.", stage=0)
        return analyze_rules(message)

    providers = get_provider_chain()
    
    for provider in providers:
        p_name = provider["name"]
        try:
            if broadcast_callback:
                await broadcast_callback("Router", f"Attempting reasoning with {p_name}...", stage=1)
                
            # Execute with timeout
            verdict = await asyncio.wait_for(
                execute_adk_pipeline(provider, message, broadcast_callback),
                timeout=25.0
            )
            if broadcast_callback:
                await broadcast_callback("Router", f"Success with {p_name}!", stage=4)
            return verdict
        except Exception as err:
            logger.info(f"Provider {p_name} failed: {err}. Cascading to next fallback.")
            if broadcast_callback:
                await broadcast_callback("Router", f"{p_name} failed. Cascading to fallback...", stage=1)
            continue

    # Final guaranteed fallback: deterministic rules engine
    if broadcast_callback:
        await broadcast_callback("Router", "All LLMs unavailable or bypassed. Using rules.", stage=4)
    return analyze_rules(message)
